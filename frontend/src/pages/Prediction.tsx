import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { predictSegment, type PredictionResponse, type PredictionRequest } from '../api/predictionApi';
import { SegmentBadge } from '../components/SegmentBadge';
import { RFMCard } from '../components/RFMCard';
import {
  LineChart,
  Send,
  UserPlus,
  // TrendingUp, 
  AlertCircle,
  Clock,
  CheckCircle,
  ShieldAlert,
  ArrowRight
} from 'lucide-react';

import { Header } from '../components/Header';

interface PredictionProps {
  onMenuToggle: () => void;
}

export const Prediction: React.FC<PredictionProps> = ({ onMenuToggle }) => {
  const navigate = useNavigate();

  // Form fields
  const [customerId, setCustomerId] = useState<string>('');
  const [invoiceNo, setInvoiceNo] = useState<string>('');
  const [invoiceDate, setInvoiceDate] = useState<string>(() => {
    const today = new Date();
    return today.toISOString().split('T')[0];
  });
  const [quantity, setQuantity] = useState<string>('1');
  const [unitPrice, setUnitPrice] = useState<string>('9.99');

  // Page states
  const [submitting, setSubmitting] = useState(false);
  const [formErrors, setFormErrors] = useState<Record<string, string>>({});
  const [apiError, setApiError] = useState<string | null>(null);
  const [result, setResult] = useState<PredictionResponse | null>(null);

  const validate = (): boolean => {
    const errors: Record<string, string> = {};

    if (customerId.trim()) {
      const idNum = Number(customerId);
      if (isNaN(idNum) || idNum <= 0 || !Number.isInteger(idNum)) {
        errors.customerId = 'Customer ID must be a positive integer.';
      }
    }

    if (!invoiceNo.trim()) {
      errors.invoiceNo = 'Invoice number is required.';
    }

    if (!invoiceDate) {
      errors.invoiceDate = 'Invoice date is required.';
    }

    const qtyNum = Number(quantity);
    if (isNaN(qtyNum) || !Number.isInteger(qtyNum) || qtyNum === 0) {
      errors.quantity = 'Quantity must be a non-zero integer.';
    }

    const priceNum = Number(unitPrice);
    if (isNaN(priceNum) || priceNum < 0) {
      errors.unitPrice = 'Unit price must be a positive number.';
    }

    setFormErrors(errors);
    return Object.keys(errors).length === 0;
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!validate()) return;

    setSubmitting(true);
    setApiError(null);
    // Keep past result until new prediction succeeds

    const payload: PredictionRequest = {
      customer_id: customerId.trim() ? parseInt(customerId, 10) : null,
      invoice_no: invoiceNo,
      invoice_date: invoiceDate,
      quantity: parseInt(quantity, 10),
      unit_price: parseFloat(unitPrice),
    };

    try {
      const data = await predictSegment(payload);
      setResult(data);
      // Auto-fill Customer ID field for ease if it was generated by the backend
      if (!customerId.trim()) {
        setCustomerId(data.customer_id.toString());
      }
    } catch (err: any) {
      console.error(err);
      const detail = err?.response?.data?.detail;
      setApiError(
        typeof detail === 'string' 
          ? `Failed to calculate prediction: ${detail}` 
          : 'Unable to calculate prediction. Please make sure the API is active.'
      );
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="flex flex-col min-h-screen">
      <Header
        title="Customer Segment Prediction"
        subtitle="Submit a customer transaction to calculate updated RFM metrics and predict the customer's current segment."
        onMenuToggle={onMenuToggle}
      />
      <div className="p-6 lg:p-8 space-y-6 flex-1 overflow-y-auto animate-fadeIn text-left">

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
        {/* Left Side: Prediction Form */}
        <div className="lg:col-span-5 p-6 rounded-xl border border-[var(--border-color)] bg-[var(--bg-secondary)] shadow-sm text-left space-y-6">
          <div className="flex items-center gap-2 pb-3 border-b border-[var(--border-color)]">
            <LineChart className="text-[var(--accent)]" size={18} />
            <h3 className="text-base font-semibold text-[var(--text-primary)]">New Transaction</h3>
          </div>

          <form onSubmit={handleSubmit} className="space-y-4">
            {/* Customer ID */}
            <div>
              <label className="block text-xs font-semibold text-[var(--text-secondary)] uppercase tracking-wider mb-1.5">
                Customer ID <span className="text-[var(--text-tertiary)] lowercase font-normal">(optional)</span>
              </label>
              <input
                type="text"
                value={customerId}
                onChange={(e) => setCustomerId(e.target.value)}
                placeholder="Leave blank to auto-generate"
                disabled={submitting}
                className={`block w-full px-3 py-2 border rounded-lg bg-[var(--bg-primary)]/50 text-sm text-[var(--text-primary)] placeholder-[var(--text-tertiary)] focus:outline-hidden focus:ring-1 focus:ring-[var(--accent)] focus:border-[var(--accent)] transition-all ${
                  formErrors.customerId ? 'border-red-500 ring-1 ring-red-500' : 'border-[var(--border-color)]'
                }`}
              />
              {formErrors.customerId && (
                <p className="text-xs text-red-500 mt-1 flex items-center gap-1">
                  <AlertCircle size={12} /> {formErrors.customerId}
                </p>
              )}
            </div>

            {/* Invoice Number */}
            <div>
              <label className="block text-xs font-semibold text-[var(--text-secondary)] uppercase tracking-wider mb-1.5">
                Invoice Number
              </label>
              <input
                type="text"
                value={invoiceNo}
                onChange={(e) => setInvoiceNo(e.target.value)}
                placeholder="e.g. 536365"
                disabled={submitting}
                className={`block w-full px-3 py-2 border rounded-lg bg-[var(--bg-primary)]/50 text-sm text-[var(--text-primary)] placeholder-[var(--text-tertiary)] focus:outline-hidden focus:ring-1 focus:ring-[var(--accent)] focus:border-[var(--accent)] transition-all ${
                  formErrors.invoiceNo ? 'border-red-500 ring-1 ring-red-500' : 'border-[var(--border-color)]'
                }`}
              />
              {formErrors.invoiceNo && (
                <p className="text-xs text-red-500 mt-1 flex items-center gap-1">
                  <AlertCircle size={12} /> {formErrors.invoiceNo}
                </p>
              )}
            </div>

            {/* Invoice Date */}
            <div>
              <label className="block text-xs font-semibold text-[var(--text-secondary)] uppercase tracking-wider mb-1.5">
                Invoice Date
              </label>
              <input
                type="date"
                value={invoiceDate}
                onChange={(e) => setInvoiceDate(e.target.value)}
                disabled={submitting}
                className={`block w-full px-3 py-2 border rounded-lg bg-[var(--bg-primary)]/50 text-sm text-[var(--text-primary)] focus:outline-hidden focus:ring-1 focus:ring-[var(--accent)] focus:border-[var(--accent)] transition-all ${
                  formErrors.invoiceDate ? 'border-red-500 ring-1 ring-red-500' : 'border-[var(--border-color)]'
                }`}
              />
              {formErrors.invoiceDate && (
                <p className="text-xs text-red-500 mt-1 flex items-center gap-1">
                  <AlertCircle size={12} /> {formErrors.invoiceDate}
                </p>
              )}
            </div>

            {/* Split Quantity and Unit Price */}
            <div className="grid grid-cols-2 gap-4">
              <div>
                <label className="block text-xs font-semibold text-[var(--text-secondary)] uppercase tracking-wider mb-1.5">
                  Quantity
                </label>
                <input
                  type="number"
                  value={quantity}
                  onChange={(e) => setQuantity(e.target.value)}
                  placeholder="e.g. 6"
                  disabled={submitting}
                  className={`block w-full px-3 py-2 border rounded-lg bg-[var(--bg-primary)]/50 text-sm text-[var(--text-primary)] focus:outline-hidden focus:ring-1 focus:ring-[var(--accent)] focus:border-[var(--accent)] transition-all ${
                    formErrors.quantity ? 'border-red-500 ring-1 ring-red-500' : 'border-[var(--border-color)]'
                  }`}
                />
                {formErrors.quantity && (
                  <p className="text-xs text-red-500 mt-1 flex items-center gap-1">
                    <AlertCircle size={12} /> {formErrors.quantity}
                  </p>
                )}
              </div>

              <div>
                <label className="block text-xs font-semibold text-[var(--text-secondary)] uppercase tracking-wider mb-1.5">
                  Unit Price ($)
                </label>
                <input
                  type="number"
                  step="0.01"
                  value={unitPrice}
                  onChange={(e) => setUnitPrice(e.target.value)}
                  placeholder="e.g. 2.55"
                  disabled={submitting}
                  className={`block w-full px-3 py-2 border rounded-lg bg-[var(--bg-primary)]/50 text-sm text-[var(--text-primary)] focus:outline-hidden focus:ring-1 focus:ring-[var(--accent)] focus:border-[var(--accent)] transition-all ${
                    formErrors.unitPrice ? 'border-red-500 ring-1 ring-red-500' : 'border-[var(--border-color)]'
                  }`}
                />
                {formErrors.unitPrice && (
                  <p className="text-xs text-red-500 mt-1 flex items-center gap-1">
                    <AlertCircle size={12} /> {formErrors.unitPrice}
                  </p>
                )}
              </div>
            </div>

            {/* Form Submit Error */}
            {apiError && (
              <div className="p-3 bg-red-50 dark:bg-red-950/20 text-red-600 dark:text-red-400 border border-red-200 dark:border-red-900/30 rounded-lg text-xs flex gap-2">
                <ShieldAlert size={16} className="shrink-0" />
                <span>{apiError}</span>
              </div>
            )}

            {/* Submit Button */}
            <button
              type="submit"
              disabled={submitting}
              className="w-full flex items-center justify-center gap-2 py-2.5 px-4 rounded-lg bg-[var(--accent)] hover:bg-[var(--accent-hover)] text-white text-sm font-semibold transition-all cursor-pointer disabled:opacity-70"
            >
              {submitting ? (
                <>
                  <Clock size={16} className="animate-spin" />
                  Calculating Segment...
                </>
              ) : (
                <>
                  <Send size={16} />
                  Calculate Prediction
                </>
              )}
            </button>
          </form>
        </div>

        {/* Right Side: Prediction Result Panel */}
        <div className="lg:col-span-7 space-y-6">
          {result ? (
            <div className="p-6 rounded-xl border border-[var(--border-color)] bg-[var(--bg-secondary)] shadow-sm text-left space-y-6 animate-scaleIn">
              <div className="flex justify-between items-center pb-3 border-b border-[var(--border-color)]">
                <div className="flex items-center gap-2">
                  <CheckCircle className="text-emerald-500" size={20} />
                  <h3 className="text-base font-semibold text-[var(--text-primary)]">Clustering Output</h3>
                </div>
                <button
                  onClick={() => navigate(`/customer/${result.customer_id}`)}
                  className="flex items-center gap-1.5 text-xs font-semibold text-[var(--accent)] hover:text-[var(--accent-hover)] transition-all cursor-pointer"
                >
                  View Customer
                  <ArrowRight size={14} />
                </button>
              </div>

              {/* Segment highlight */}
              <div className="p-5 rounded-xl bg-[var(--bg-primary)] border border-[var(--border-color)] flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-[var(--text-tertiary)]">Predicted Segment</span>
                  <div className="flex items-center gap-2 mt-1.5">
                    <span className="text-xl font-extrabold text-[var(--text-primary)]">
                      {result.segment}
                    </span>
                    <SegmentBadge segment={result.segment} />
                  </div>
                </div>
                <div className="text-left sm:text-right border-t sm:border-t-0 sm:border-l border-[var(--border-color)] pt-3 sm:pt-0 sm:pl-6">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-[var(--text-tertiary)]">Cluster ID</span>
                  <p className="text-lg font-mono font-bold text-[var(--text-primary)] mt-0.5">
                    Cluster {result.cluster_id}
                  </p>
                </div>
              </div>

              {/* RFM outputs */}
              <div className="space-y-4">
                <h4 className="text-xs font-bold uppercase tracking-wider text-[var(--text-secondary)]">Updated Behavioral Parameters</h4>
                <RFMCard
                  recency={result.recency}
                  frequency={result.frequency}
                  monetary={result.monetary}
                />
              </div>

              {/* Churn Prediction Sub-section (only show if returned) */}
              {(result.churn_prediction !== undefined || result.churn_probability !== undefined) && (
                <div className="p-5 rounded-xl border border-red-200 dark:border-red-900/30 bg-red-50/20 dark:bg-red-950/10 space-y-3">
                  <div className="flex items-center gap-2 text-red-600 dark:text-red-400">
                    <ShieldAlert size={16} />
                    <h4 className="text-xs font-bold uppercase tracking-wider">Churn Risk Assessment</h4>
                  </div>
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                    <div>
                      <p className="text-xs text-[var(--text-secondary)]">Churn Status</p>
                      <p className="text-sm font-semibold text-[var(--text-primary)] mt-0.5">
                        {result.churn_prediction ? 'High Risk (Likely to Churn)' : 'Stable (Low Churn Risk)'}
                      </p>
                    </div>
                    {result.churn_probability !== undefined && (
                      <div>
                        <p className="text-xs text-[var(--text-secondary)]">Churn Probability</p>
                        <p className="text-sm font-semibold text-[var(--text-primary)] mt-0.5 font-mono">
                          {(result.churn_probability * 100).toFixed(2)}%
                        </p>
                      </div>
                    )}
                  </div>
                </div>
              )}
            </div>
          ) : (
            <div className="flex flex-col items-center justify-center p-12 h-full min-h-[300px] border border-dashed border-[var(--border-color)] rounded-xl bg-[var(--bg-secondary)] shadow-sm text-center">
              <div className="p-4 bg-[var(--bg-primary)] rounded-full text-[var(--text-tertiary)] mb-4 animate-pulse">
                <UserPlus size={32} />
              </div>
              <h4 className="text-sm font-bold text-[var(--text-primary)] uppercase tracking-wider">Awaiting Intake</h4>
              <p className="text-xs text-[var(--text-secondary)] mt-2 max-w-sm">
                Fill out the transaction details form and click <strong>Calculate Prediction</strong> to run the segmentation and forecasting models.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  </div>
);
};
export default Prediction;
